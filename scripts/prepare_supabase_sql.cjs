// Build the one-time Supabase setup from the reviewed PostgreSQL source files.
// This writes a local SQL file only. It never connects to or changes a database.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
function transactionBody(file) {
  const source = fs.readFileSync(path.join(root, file), 'utf8');
  const start = source.indexOf('\nBEGIN;\n');
  const end = source.lastIndexOf('\nCOMMIT;');
  if (start < 0 || end < start || source.slice(end).trim() !== 'COMMIT;') {
    throw new Error(`Expected one outer transaction in ${file}`);
  }
  return source.slice(start + '\nBEGIN;\n'.length, end).trim();
}
const output = `-- Generated by node scripts/prepare_supabase_sql.cjs. Do not edit manually.
-- Supabase setup: NEW Areva application schema only; apply ONCE.
-- Check the selected project in the Dashboard before running.
-- Creates 19 tables and 8 categories inside areva, not public or auth.
-- Does not migrate JSON content, create a login, or connect the website.
-- If areva already exists, STOP and inspect it; do not drop existing data.
BEGIN;

-- Earlier public-schema installs need an explicit migration, not a second copy.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM pg_tables WHERE schemaname = 'public' AND tablename IN (
      'categories', 'products', 'product_pack_sizes', 'product_surfaces',
      'dealers', 'dealer_badges', 'landing_images', 'colours', 'colour_pairings',
      'shade_cards', 'gallery_projects', 'gallery_photos', 'gallery_ads', 'gallery_reviews',
      'site_state', 'enquiries', 'users', 'user_login_identifiers', 'activity_events'
    )
  ) THEN
    RAISE EXCEPTION 'Existing application table names found in public. Stop and inspect before migrating.';
  END IF;
END;
$$;
CREATE SCHEMA areva;
SET LOCAL search_path = areva, pg_catalog;

${transactionBody('database/schema.sql')}

${transactionBody('database/seed-categories.sql')}

-- Trigger lookups must keep working when the caller's search_path is public.
ALTER FUNCTION areva.sync_user_login_identifiers()
  SET search_path = pg_catalog, pg_temp;

-- Access stays behind the Express backend, not Supabase browser API roles.
-- RLS has no browser policies; the table owner can still administer/import data.
DO $$
DECLARE target record;
BEGIN
  FOR target IN
    SELECT tablename FROM pg_tables WHERE schemaname = 'areva'
  LOOP
    EXECUTE format('ALTER TABLE areva.%I ENABLE ROW LEVEL SECURITY', target.tablename);
  END LOOP;
END;
$$;
REVOKE ALL ON SCHEMA areva FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON ALL TABLES IN SCHEMA areva FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA areva FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA areva FROM PUBLIC, anon, authenticated, service_role;

COMMIT;

-- Verification: expect 19, 8 and 19 respectively.
SELECT count(*) AS areva_tables FROM pg_tables WHERE schemaname = 'areva';
SELECT count(*) AS categories FROM areva.categories;
SELECT count(*) AS tables_with_rls FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'areva' AND c.relkind = 'r' AND c.relrowsecurity;
`;
fs.writeFileSync(path.join(root, 'database/supabase-setup.sql'), output);
console.log('Prepared database/supabase-setup.sql locally. No database was changed.');
